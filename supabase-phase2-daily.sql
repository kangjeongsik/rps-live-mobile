BEGIN;

ALTER TABLE public.rps_event_runtime ADD COLUMN IF NOT EXISTS listed boolean NOT NULL DEFAULT false;
ALTER TABLE public.rps_push_subscriptions ADD COLUMN IF NOT EXISTS legacy_enabled boolean NOT NULL DEFAULT true;

CREATE TABLE IF NOT EXISTS public.daily_schedules (
  id text PRIMARY KEY,
  game_type text NOT NULL DEFAULT 'rps_tournament',
  start_time time NOT NULL DEFAULT '21:00',
  min_players integer NOT NULL DEFAULT 2 CHECK (min_players BETWEEN 2 AND 200),
  preparation_seconds integer NOT NULL DEFAULT 10 CHECK (preparation_seconds BETWEEN 1 AND 600),
  wait_minutes integer NOT NULL DEFAULT 60 CHECK (wait_minutes BETWEEN 1 AND 180),
  enabled boolean NOT NULL DEFAULT true
);

INSERT INTO public.daily_schedules(id) VALUES ('daily-rps') ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS public.daily_occurrences (
  event_id uuid PRIMARY KEY REFERENCES public.rps_event_runtime(event_id) ON DELETE RESTRICT,
  schedule_id text NOT NULL REFERENCES public.daily_schedules(id),
  service_date date NOT NULL,
  game_type text NOT NULL,
  scheduled_at timestamptz NOT NULL,
  min_players integer NOT NULL,
  preparation_seconds integer NOT NULL,
  wait_minutes integer NOT NULL,
  status text NOT NULL DEFAULT 'scheduled'
    CHECK (status IN ('scheduled','open','playing','finished','cancelled','expired')),
  opened_at timestamptz,
  ready_at timestamptz,
  wait_until timestamptz,
  started_at timestamptz,
  ended_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (schedule_id, service_date)
);

CREATE INDEX IF NOT EXISTS daily_occurrences_due_idx
  ON public.daily_occurrences(status, scheduled_at) WHERE status IN ('scheduled','open');

CREATE TABLE IF NOT EXISTS public.daily_reservations (
  id uuid PRIMARY KEY,
  event_id uuid NOT NULL REFERENCES public.daily_occurrences(event_id),
  device_hash text NOT NULL,
  reserved_at timestamptz NOT NULL,
  status text NOT NULL CHECK (status IN ('reserved','cancelled')),
  notify boolean NOT NULL DEFAULT false,
  cancelled_at timestamptz,
  participant_id text,
  joined_at timestamptz,
  UNIQUE (event_id,device_hash)
);

CREATE TABLE IF NOT EXISTS public.daily_participations (
  event_id uuid NOT NULL REFERENCES public.daily_occurrences(event_id),
  device_hash text NOT NULL,
  participant_id text NOT NULL,
  joined_at timestamptz NOT NULL,
  PRIMARY KEY (event_id,device_hash)
);

CREATE INDEX IF NOT EXISTS daily_participations_device_idx
  ON public.daily_participations(device_hash,event_id);

CREATE TABLE IF NOT EXISTS public.daily_notification_preferences (
  device_hash text PRIMARY KEY,
  daily_start boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS public.daily_notification_jobs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id uuid NOT NULL REFERENCES public.daily_occurrences(event_id),
  device_hash text NOT NULL,
  kind text NOT NULL DEFAULT 'daily_start',
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending','retry','sent','failed','skipped')),
  attempts integer NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL,
  sent_at timestamptz,
  last_error text,
  UNIQUE (event_id,device_hash,kind)
);

CREATE INDEX IF NOT EXISTS daily_jobs_due_idx ON public.daily_notification_jobs(next_attempt_at)
  WHERE status IN ('pending','retry');

CREATE TABLE IF NOT EXISTS public.daily_execution_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id uuid NOT NULL REFERENCES public.daily_occurrences(event_id),
  execution_key text NOT NULL UNIQUE,
  action text NOT NULL,
  executed_at timestamptz NOT NULL
);

ALTER TABLE public.daily_schedules ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_occurrences ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_reservations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_participations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_notification_preferences ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_notification_jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_execution_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.daily_schedules,public.daily_occurrences,public.daily_reservations,
  public.daily_participations,public.daily_notification_preferences,public.daily_notification_jobs,public.daily_execution_log
  FROM PUBLIC,anon,authenticated;

COMMIT;
