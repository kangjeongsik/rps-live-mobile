BEGIN;

CREATE TABLE IF NOT EXISTS public.sponsor_companies (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL, brand text NOT NULL, industry text NOT NULL,
  contact_name text NOT NULL DEFAULT '', contact_info text NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '', logo_url text NOT NULL DEFAULT '',
  image_url text NOT NULL DEFAULT '', website_url text NOT NULL DEFAULT '',
  enabled boolean NOT NULL DEFAULT true, internal_note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.sponsor_campaigns (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  company_id uuid NOT NULL REFERENCES public.sponsor_companies(id),
  event_id uuid UNIQUE REFERENCES public.rps_event_runtime(event_id),
  type text NOT NULL CHECK (type IN ('quiz','mission','rps')),
  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft','scheduled','open','active','paused','completed','cancelled')),
  title text NOT NULL, description text NOT NULL DEFAULT '', image_url text NOT NULL DEFAULT '',
  join_terms text NOT NULL DEFAULT '', ad_goal text NOT NULL DEFAULT '',
  estimated_reach integer CHECK (estimated_reach >= 0), ad_product_id uuid, coupon_policy_id uuid,
  opens_at timestamptz NOT NULL, starts_at timestamptz NOT NULL, ends_at timestamptz NOT NULL,
  allow_retry boolean NOT NULL DEFAULT false,
  published_at timestamptz, paused_at timestamptz, completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (opens_at <= starts_at AND starts_at < ends_at),
  CHECK ((type='rps') = (event_id IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS sponsor_campaigns_status_dates_idx
  ON public.sponsor_campaigns(status,opens_at,starts_at,ends_at);
CREATE INDEX IF NOT EXISTS sponsor_campaigns_company_idx ON public.sponsor_campaigns(company_id);

CREATE TABLE IF NOT EXISTS public.campaign_participants (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  campaign_id uuid NOT NULL REFERENCES public.sponsor_campaigns(id),
  device_hash text NOT NULL, display_name text NOT NULL,
  engine_player_id text, joined_at timestamptz NOT NULL,
  UNIQUE(campaign_id,device_hash), UNIQUE(campaign_id,id), UNIQUE(campaign_id,engine_player_id)
);
CREATE INDEX IF NOT EXISTS campaign_participants_device_idx ON public.campaign_participants(device_hash,campaign_id);

CREATE TABLE IF NOT EXISTS public.campaign_quiz_questions (
  campaign_id uuid NOT NULL REFERENCES public.sponsor_campaigns(id),
  position integer NOT NULL CHECK (position>0), prompt text NOT NULL, choices jsonb NOT NULL,
  correct_index integer NOT NULL CHECK(correct_index>=0), points integer NOT NULL CHECK(points>0),
  PRIMARY KEY(campaign_id,position)
);
CREATE TABLE IF NOT EXISTS public.campaign_quiz_submissions (
  campaign_id uuid NOT NULL, participant_id uuid NOT NULL, request_id uuid NOT NULL,
  answers jsonb NOT NULL, score integer NOT NULL CHECK(score>=0), submitted_at timestamptz NOT NULL,
  PRIMARY KEY(campaign_id,participant_id,request_id),
  FOREIGN KEY(campaign_id,participant_id) REFERENCES public.campaign_participants(campaign_id,id)
);
CREATE INDEX IF NOT EXISTS campaign_quiz_score_idx
  ON public.campaign_quiz_submissions(campaign_id,score DESC,submitted_at);

CREATE TABLE IF NOT EXISTS public.campaign_missions (
  campaign_id uuid NOT NULL REFERENCES public.sponsor_campaigns(id),
  day integer NOT NULL CHECK(day BETWEEN 1 AND 31), title text NOT NULL, description text NOT NULL,
  kind text NOT NULL CHECK(kind IN ('daily_quiz','content_check')),
  content text NOT NULL, prompt text NOT NULL, choices jsonb NOT NULL,
  correct_index integer NOT NULL CHECK(correct_index>=0),
  PRIMARY KEY(campaign_id,day)
);
CREATE TABLE IF NOT EXISTS public.campaign_mission_progress (
  campaign_id uuid NOT NULL, participant_id uuid NOT NULL, day integer NOT NULL,
  request_id uuid NOT NULL, completed_at timestamptz NOT NULL,
  PRIMARY KEY(campaign_id,participant_id,day),
  UNIQUE(campaign_id,participant_id,request_id),
  FOREIGN KEY(campaign_id,participant_id) REFERENCES public.campaign_participants(campaign_id,id),
  FOREIGN KEY(campaign_id,day) REFERENCES public.campaign_missions(campaign_id,day)
);

CREATE TABLE IF NOT EXISTS public.campaign_mission_attempts (
  campaign_id uuid NOT NULL, participant_id uuid NOT NULL, day integer NOT NULL,
  request_id uuid NOT NULL, correct boolean NOT NULL, submitted_at timestamptz NOT NULL,
  PRIMARY KEY(campaign_id,participant_id,request_id),
  FOREIGN KEY(campaign_id,participant_id) REFERENCES public.campaign_participants(campaign_id,id),
  FOREIGN KEY(campaign_id,day) REFERENCES public.campaign_missions(campaign_id,day)
);

CREATE TABLE IF NOT EXISTS public.campaign_activity_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id uuid NOT NULL REFERENCES public.sponsor_campaigns(id),
  action text NOT NULL, source text NOT NULL, detail text NOT NULL DEFAULT '',
  occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS campaign_activity_recent_idx ON public.campaign_activity_logs(campaign_id,id DESC);

-- Uses the same hashed browser identity as DAILY. Consent is channel-specific.
CREATE TABLE IF NOT EXISTS public.campaign_notification_preferences (
  device_hash text PRIMARY KEY,
  event_updates boolean NOT NULL DEFAULT false,
  advertising boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now()
);

DO $$
DECLARE table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['sponsor_companies','sponsor_campaigns','campaign_participants',
    'campaign_quiz_questions','campaign_quiz_submissions','campaign_missions','campaign_mission_progress',
    'campaign_mission_attempts','campaign_activity_logs','campaign_notification_preferences']
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC, anon, authenticated', table_name);
  END LOOP;
END $$;

COMMIT;
